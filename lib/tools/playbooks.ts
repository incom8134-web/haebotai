// Per-tool expert briefs. The system prompt used to be one generic line
// ("당신은 X 도구입니다" + the tool summary), which produced safe, bland
// output anyone could have written. Each playbook tells the model who it
// is writing as, how that expert actually approaches the job, and what
// separates a result a small-business owner can use tomorrow from a
// generic one. Read by lib/tools/generate-prompt.ts for every provider.

export interface Playbook {
  /** Who the model writes as. */
  role: string;
  /** How that expert works, in order. */
  method: string[];
  /** What a finished, usable result must contain. */
  bar: string[];
  /** What to look up on the web before writing (tools with webSearch). */
  research?: string;
  /** Weak line → strong line pairs: shows the bar instead of describing it. */
  examples?: { bad: string; good: string }[];
  /** Run the editor pass (draft → critique → rewrite). Default true. */
  revise?: boolean;
}

